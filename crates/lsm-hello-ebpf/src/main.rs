//! Milestone 1 smoke test: prove a BPF LSM program loads and runs.
//!
//! Hooks `file_open` and logs the path of every file opened by a process whose
//! comm is `cat`. Never denies anything.
//!
//! Needs `src/vmlinux.rs` for `struct file`. Generate it on the VM:
//!     aya-tool generate file > src/vmlinux.rs

#![no_std]
#![no_main]

#[allow(
    non_upper_case_globals,
    non_snake_case,
    non_camel_case_types,
    dead_code,
    clippy::all // generated by aya-tool
)]
mod vmlinux;

use aya_ebpf::{
    helpers::{bpf_get_current_comm, bpf_get_current_pid_tgid, gen::bpf_d_path},
    macros::{lsm, map},
    maps::PerCpuArray,
    programs::LsmContext,
};
use aya_log_ebpf::info;
use vmlinux::file;

const PATH_LEN: usize = 256;

/// Scratch space for the path; too big to keep on the 512-byte BPF stack.
#[map]
static PATH_BUF: PerCpuArray<[u8; PATH_LEN]> = PerCpuArray::with_max_entries(1, 0);

/// Always allows. Returning a constant 0 (rather than passing through an
/// earlier verdict inside a Result) keeps R0 provably in [-4095, 0], which the
/// verifier requires of LSM programs.
#[lsm(hook = "file_open")]
pub fn file_open(ctx: LsmContext) -> i32 {
    let _ = try_file_open(&ctx);
    0
}

fn try_file_open(ctx: &LsmContext) -> Result<(), i64> {
    // int file_open(struct file *file)
    let comm = bpf_get_current_comm()?;
    if &comm[..4] != b"cat\0" {
        return Ok(());
    }

    let f: *const file = unsafe { ctx.arg(0) };
    let buf = unsafe { &mut *PATH_BUF.get_ptr_mut(0).ok_or(0i64)? };
    let len = unsafe {
        bpf_d_path(
            core::ptr::addr_of!((*f).f_path) as *mut _,
            buf.as_mut_ptr() as *mut _,
            PATH_LEN as u32,
        )
    };
    if len <= 0 {
        return Ok(());
    }
    // len includes the trailing NUL.
    let len = (len as usize - 1).min(PATH_LEN - 1);
    let path = unsafe { core::str::from_utf8_unchecked(&buf[..len]) };
    let pid = (bpf_get_current_pid_tgid() >> 32) as u32;
    info!(ctx, "file_open pid={} comm=cat path={}", pid, path);
    Ok(())
}

#[cfg(not(test))]
#[panic_handler]
fn panic(_info: &core::panic::PanicInfo) -> ! {
    loop {}
}
