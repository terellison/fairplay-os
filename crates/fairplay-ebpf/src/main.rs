//! Kernel side of the protected-process primitive (milestone 3).
//!
//! One module per LSM hook, under `hooks/`. Each hook decides with the shared
//! helpers in `domain` (is the target protected, is the caller in its
//! domain, record the violation) and the maps in `maps`. Adding a hook means
//! one new file in `hooks/`, one `mod` line in `hooks/mod.rs`, and one entry
//! in fairplayd's `LSM_PROGRAMS`.
//!
//! `follow` (milestone 5) keeps PROTECTED in step with the game's process
//! tree. Its tracing programs are attached from fairplayd's
//! `TRACING_PROGRAMS`.
//!
//! `readers` (milestone 9) decides who may read a protected process besides
//! itself: processes that exec'd a manifest-named reader file. Its tracing
//! program is in `TRACING_PROGRAMS` too.
//!
//! `self_protect` (milestone 6) keeps every other process, root included,
//! away from fairplayd itself while it runs with `--self-protect`.
//!
//! Needs `src/vmlinux.rs` for kernel struct layouts. Generate it on the VM:
//!     aya-tool generate task_struct > src/vmlinux.rs

